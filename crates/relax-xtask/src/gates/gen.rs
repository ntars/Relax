//! 由 contracts/*.json 生成 ui/src/gen/*.ts；check-gen 逐字节校验生成物未过期。

use super::GateResult;
use serde_json::Value;
use std::path::PathBuf;

const HEADER: &str = "// @generated by xtask gen-ts — DO NOT EDIT\n";

fn workspace_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read_contract(name: &str) -> Value {
    let path = workspace_root().join("contracts").join(name);
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("读取 {} 失败: {}", name, e));
    text.parse().unwrap_or_else(|e| panic!("解析 {} 失败: {}", name, e))
}

fn ts_string(s: &str) -> String {
    let escaped = s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n");
    format!("\"{}\"", escaped)
}

fn error_codes_ts() -> String {
    let v = read_contract("error-codes.json");
    let mut out = String::from(HEADER);
    out.push_str("export const ERROR_CODES = {\n");
    if let Some(list) = v.get("errors").and_then(|e| e.as_array()) {
        for item in list {
            let code = item.get("code").and_then(|x| x.as_u64()).unwrap_or(0);
            let name = item.get("name").and_then(|x| x.as_str()).unwrap_or("");
            let http = item.get("http").and_then(|x| x.as_u64()).unwrap_or(0);
            let message = item.get("message").and_then(|x| x.as_str()).unwrap_or("");
            let action = item.get("action").and_then(|x| x.as_str()).unwrap_or("");
            let retryable = item.get("retryable").and_then(|x| x.as_bool()).unwrap_or(false);
            out.push_str(&format!(
                "  {}: {{ code: {}, name: {}, http: {}, message: {}, action: {}, retryable: {} }},\n",
                code, code, ts_string(name), http, ts_string(message), ts_string(action), retryable
            ));
        }
    }
    out.push_str("} as const;\n\n");
    out.push_str("export type ErrorCode = keyof typeof ERROR_CODES;\n");
    out
}

fn capabilities_ts() -> String {
    let v = read_contract("capabilities.json");
    let mut out = String::from(HEADER);
    let roles: Vec<String> = v.get("roles")
        .and_then(|r| r.as_array())
        .map(|a| a.iter().filter_map(|x| x.as_str().map(String::from)).collect())
        .unwrap_or_default();
    out.push_str("export const ROLES = [");
    out.push_str(&roles.iter().map(|r| ts_string(r)).collect::<Vec<_>>().join(", "));
    out.push_str("] as const;\n");
    out.push_str("export type Role = typeof ROLES[number];\n\n");
    out.push_str("export const CAPABILITIES: Record<string, readonly Role[]> = {\n");
    if let Some(caps) = v.get("capabilities").and_then(|c| c.as_object()) {
        let mut keys: Vec<&String> = caps.keys().collect();
        keys.sort();
        for key in keys {
            let granted = caps.get(key).and_then(|g| g.as_array()).map(|a| {
                a.iter().filter_map(|x| x.as_str()).map(ts_string).collect::<Vec<_>>().join(", ")
            }).unwrap_or_default();
            out.push_str(&format!("  {}: [{}],\n", ts_string(key), granted));
        }
    }
    out.push_str("};\n");
    out
}

fn generated() -> Vec<(&'static str, String)> {
    vec![("error-codes.ts", error_codes_ts()), ("capabilities.ts", capabilities_ts())]
}

pub fn gen_ts() -> super::super::Exit {
    let dir = workspace_root().join("ui/src/gen");
    if let Err(e) = std::fs::create_dir_all(&dir) {
        eprintln!("创建 ui/src/gen 失败: {}", e);
        return super::super::Exit::BuildFailed;
    }
    for (name, content) in generated() {
        let path = dir.join(name);
        if let Err(e) = std::fs::write(&path, content) {
            eprintln!("写入 {} 失败: {}", name, e);
            return super::super::Exit::BuildFailed;
        }
        println!("已生成 ui/src/gen/{}", name);
    }
    super::super::Exit::Ok
}

pub fn check_gen() -> GateResult {
    let dir = workspace_root().join("ui/src/gen");
    let mut diffs = Vec::new();
    for (name, expected) in generated() {
        let path = dir.join(name);
        match std::fs::read_to_string(&path) {
            Ok(actual) if actual == expected => {}
            Ok(_) => diffs.push(format!("{} 已过期", name)),
            Err(_) => diffs.push(format!("{} 缺失", name)),
        }
    }
    if diffs.is_empty() {
        GateResult::pass("ui/src/gen 与契约逐字节一致")
    } else {
        GateResult::fail(format!("生成物过期: {}（运行 cargo xtask gen-ts）", diffs.join("; ")))
    }
}
