//! C1.1 验收：信封四段齐全 + traceId + 错误映射 + JSON 日志（手册 3.2 / 10.5）。
//! 用 tower::ServiceExt::oneshot 直接驱动 Router，不占端口。

use axum::{
    body::Body,
    http::{header, Request, StatusCode},
    response::{IntoResponse, Response},
};
use relax_contracts::Envelope;
use relax_server::{
    app,
    common::{
        err_envelope, ok_envelope, trace_id_from_headers, AppError,
    },
    state::{AppInfo, AppState},
};
use serde_json::{json, Value};
use std::sync::Arc;
use tokio::sync::RwLock;
use tower::ServiceExt;

fn test_state() -> AppState {
    AppState {
        app_info: Arc::new(RwLock::new(AppInfo { version: "1.0.0".to_string() })),
    }
}

async fn request(uri: &str, trace: Option<&str>) -> Response {
    let mut builder = Request::builder().uri(uri);
    if let Some(t) = trace {
        builder = builder.header("x-request-id", t);
    }
    app(test_state())
        .oneshot(builder.body(Body::empty()).unwrap())
        .await
        .unwrap()
}

async fn envelope_of(resp: Response) -> Envelope<Value> {
    let bytes = axum::body::to_bytes(resp.into_body(), 1024 * 1024).await.unwrap();
    serde_json::from_slice(&bytes).unwrap()
}

#[tokio::test]
async fn health_returns_full_envelope() {
    let resp = request("/api/v1/health", Some("trace-fixed-001")).await;
    assert_eq!(resp.status(), StatusCode::OK);
    assert_eq!(resp.headers()["x-trace-id"], "trace-fixed-001");
    let env = envelope_of(resp).await;
    assert!(env.ok);
    assert!(env.data.is_some());
    assert!(env.error.is_none());
    assert_eq!(env.meta.trace_id, "trace-fixed-001");
    assert_eq!(env.meta.contract_version, "1.0.0");
    assert!(!env.meta.server_time.is_empty());
}

#[tokio::test]
async fn trace_id_autogenerated_when_header_absent() {
    let resp = request("/api/v1/health", None).await;
    let trace = resp.headers()["x-trace-id"].to_str().unwrap().to_string();
    assert_eq!(trace.len(), 36);
    let env = envelope_of(resp).await;
    assert_eq!(env.meta.trace_id, trace);
}

#[tokio::test]
async fn app_error_maps_http_status_and_contract_fields() {
    let resp = AppError::new(1006, "trace-err-001").into_response();
    assert_eq!(resp.status(), StatusCode::FORBIDDEN);
    let env = envelope_of(resp).await;
    assert!(!env.ok);
    assert!(env.data.is_none());
    let err = env.error.unwrap();
    assert_eq!(err.code, 1006);
    assert_eq!(err.name, "FORBIDDEN");
    assert!(!err.retryable);
    assert_eq!(err.trace_id, "trace-err-001");
    assert_eq!(env.meta.trace_id, "trace-err-001");
}

#[tokio::test]
async fn envelope_constructors_keep_data_error_exclusive() {
    let ok = ok_envelope(json!({"k": 1}), "t-ok");
    assert!(ok.ok);
    assert!(ok.error.is_none());
    let err = err_envelope::<Value>(1001, "t-err");
    assert!(!err.ok);
    assert!(err.data.is_none());
    assert_eq!(err.error.unwrap().code, 1001);
}

#[test]
fn trace_id_from_header_uses_or_generates() {
    let mut headers = header::HeaderMap::new();
    headers.insert("x-request-id", header::HeaderValue::from_static("hdr-1"));
    assert_eq!(trace_id_from_headers(&headers).0, "hdr-1");
    let empty = header::HeaderMap::new();
    assert_eq!(trace_id_from_headers(&empty).0.len(), 36);
}

